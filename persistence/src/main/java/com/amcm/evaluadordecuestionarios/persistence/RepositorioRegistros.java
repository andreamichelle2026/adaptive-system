package com.amcm.evaluadordecuestionarios.persistence;

import com.amcm.evaluadordecuestionarios.RegistroEjecucion;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

/**
 * Guarda en una base de datos (JDBC) los RegistroEjecucion de cada corrida.
 * Solo usa la API java.sql: el driver (H2, por defecto) se agrega en el modulo launcher.
 */
public final class RepositorioRegistros {

    private static final String CREAR_TABLA = """
            CREATE TABLE IF NOT EXISTS registro_ejecucion (
                id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ejecucion_id VARCHAR(36)  NOT NULL,
                fecha        TIMESTAMP    NOT NULL,
                id_pregunta  INT          NOT NULL,
                tipo         VARCHAR(20)  NOT NULL,
                id_plugin    VARCHAR(30)  NOT NULL,
                nombre_clase VARCHAR(200) NOT NULL,
                nota         DOUBLE PRECISION NOT NULL,
                estado       VARCHAR(10)  NOT NULL
            )""";

    private static final String INSERTAR = """
            INSERT INTO registro_ejecucion
                (ejecucion_id, fecha, id_pregunta, tipo, id_plugin, nombre_clase, nota, estado)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)""";

    private final String url;
    private final String usuario;
    private final String clave;

    public RepositorioRegistros(String url, String usuario, String clave) {
        this.url = url;
        this.usuario = usuario;
        this.clave = clave;
    }

    /** Guarda todos los registros de una corrida en una sola transaccion. */
    public void guardarEjecucion(List<RegistroEjecucion> registros) throws SQLException {
        String ejecucionId = UUID.randomUUID().toString();
        Timestamp ahora = Timestamp.valueOf(LocalDateTime.now());

        try (Connection cn = DriverManager.getConnection(url, usuario, clave)) {
            try (Statement st = cn.createStatement()) {
                st.execute(CREAR_TABLA);
            }
            cn.setAutoCommit(false);
            try (PreparedStatement ps = cn.prepareStatement(INSERTAR)) {
                for (RegistroEjecucion r : registros) {
                    ps.setString(1, ejecucionId);
                    ps.setTimestamp(2, ahora);
                    ps.setInt(3, r.idPregunta());
                    ps.setString(4, r.tipo().name());
                    ps.setString(5, r.idPlugin());
                    ps.setString(6, r.nombreClase());
                    ps.setDouble(7, r.nota());
                    ps.setString(8, r.estado());
                    ps.addBatch();
                }
                ps.executeBatch();
                cn.commit();
            } catch (SQLException e) {
                cn.rollback();
                throw e;
            }
        }
    }

    /** Cuantas corridas distintas hay guardadas. */
    public int contarEjecuciones() throws SQLException {
        try (Connection cn = DriverManager.getConnection(url, usuario, clave);
             Statement st = cn.createStatement();
             ResultSet rs = st.executeQuery(
                     "SELECT COUNT(DISTINCT ejecucion_id) FROM registro_ejecucion")) {
            return rs.next() ? rs.getInt(1) : 0;
        }
    }
}
